"""python-build-standalone (PBS): resolve, pin, download, extract and trim.

The release and the sha256 of every asset used are pinned in ``wheelship.lock``
next to ``pyproject.toml`` (``pylock.toml`` is left untouched: it is a PEP 751
file). Assets are verified against the pinned hash, or against the release's
``SHA256SUMS`` the first time an asset is used.
"""

from __future__ import annotations

import dataclasses
import json
import os
import platform
import re
import shutil
import sys
import tarfile
import tempfile
import tomllib
import urllib.error
import urllib.request
from collections.abc import Iterable
from functools import cache
from pathlib import Path

from . import fetch, log, prune
from .errors import ConfigError, FetchError
from .target import Target

GITHUB = "https://github.com/astral-sh/python-build-standalone/releases/download"
LATEST_URL = (
    "https://raw.githubusercontent.com/astral-sh/python-build-standalone/"
    "latest-release/latest-release.json"
)
FLAVORS = ("install_only_stripped", "install_only")
LOCK_NAME = "wheelship.lock"

#: Groups accepted by ``[tool.wheelship.pbs].strip``.
STRIP_GROUPS = ("dev", "test", "idlelib", "tkinter")
DEFAULT_STRIP = ("dev", "test", "idlelib")


@dataclasses.dataclass(frozen=True)
class PbsConfig:
    release: str | None = None
    flavor: str = FLAVORS[0]
    strip: tuple[str, ...] = DEFAULT_STRIP


@dataclasses.dataclass(frozen=True)
class Asset:
    release: str
    name: str
    sha256: str
    version: tuple[int, int, int]
    triple: str

    @property
    def url(self) -> str:
        base = os.environ.get("WHEELSHIP_PBS_MIRROR", GITHUB).rstrip("/")
        return f"{base}/{self.release}/{self.name}"


# -- naming -----------------------------------------------------------------


def triple(os_name: str, arch: str) -> str:
    if os_name == "linux":
        return f"{arch}-unknown-linux-gnu"
    if os_name == "windows":
        return f"{arch}-pc-windows-msvc"
    if os_name == "macos":
        return f"{arch}-apple-darwin"
    raise ConfigError(f"python-build-standalone has no build for {os_name}-{arch}")


def target_triple(target: Target) -> str:
    return triple(target.os, target.arch)


def host_triple() -> str:
    machine = platform.machine().lower()
    arch = {"amd64": "x86_64", "x86_64": "x86_64", "arm64": "aarch64", "aarch64": "aarch64"}.get(
        machine
    )
    os_name = {"linux": "linux", "win32": "windows", "darwin": "macos"}.get(sys.platform)
    if arch is None or os_name is None:
        raise ConfigError(f"unsupported host platform {sys.platform}/{machine}")
    return triple(os_name, arch)


_ASSET_RE = re.compile(
    r"cpython-(?P<v>\d+\.\d+\.\d+)\+(?P<release>\d+)-(?P<triple>[a-z0-9_]+-[a-z0-9_]+-[a-z0-9_]+"
    r"(?:-[a-z0-9_]+)?)-(?P<flavor>install_only(?:_stripped)?)\.tar\.gz"
)


def select_asset(
    sums: dict[str, str],
    release: str,
    python: tuple[int, ...],
    triple_: str,
    flavor: str,
) -> Asset | None:
    """Pick the asset for ``python`` (``(3, 12)`` = newest 3.12.x, ``(3, 12, 7)`` = exact)."""
    best: Asset | None = None
    for name, sha in sums.items():
        m = _ASSET_RE.fullmatch(name)
        if not m or m["release"] != release or m["triple"] != triple_ or m["flavor"] != flavor:
            continue
        v = tuple(int(x) for x in m["v"].split("."))
        if v[: len(python)] != tuple(python):
            continue
        if best is None or v > best.version:
            best = Asset(release, name, sha, (v[0], v[1], v[2]), triple_)
    return best


# -- wheelship.lock ---------------------------------------------------------------


@dataclasses.dataclass
class Lock:
    release: str | None = None
    assets: dict[str, str] = dataclasses.field(default_factory=dict)

    @classmethod
    def load(cls, path: Path) -> Lock:
        try:
            data = tomllib.loads(path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            return cls()
        except tomllib.TOMLDecodeError as e:
            raise ConfigError(f"{path}: {e}") from None
        table = data.get("pbs", {})
        assets = {a["name"]: a["sha256"] for a in table.get("asset", [])}
        return cls(table.get("release"), assets)

    def dump(self) -> str:
        lines = [
            "# Generated by wheelship; commit this file to pin python-build-standalone.",
            "version = 1",
            "",
            "[pbs]",
            f'release = "{self.release}"',
        ]
        for name in sorted(self.assets):
            lines += ["", "[[pbs.asset]]", f'name = "{name}"', f'sha256 = "{self.assets[name]}"']
        return "\n".join(lines) + "\n"

    def save(self, path: Path) -> None:
        tmp = path.with_name(f".{path.name}.tmp")
        tmp.write_text(self.dump(), encoding="utf-8")
        os.replace(tmp, path)


# -- remote metadata ----------------------------------------------------------


def _get_text(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "wheelship"})
    try:
        with urllib.request.urlopen(req, timeout=60, context=fetch.ssl_context()) as resp:
            return resp.read().decode()  # type: ignore[no-any-return]
    except urllib.error.HTTPError as e:
        raise FetchError(f"GET {url}: HTTP {e.code}") from None
    except (urllib.error.URLError, TimeoutError) as e:
        raise FetchError(f"GET {url}: {e}") from None


@cache
def latest_release() -> str:
    tag = json.loads(_get_text(LATEST_URL))["tag"]
    if not isinstance(tag, str) or not tag.isdigit():
        raise FetchError(f"unexpected latest release tag {tag!r}")
    return tag


@cache
def release_sums(release: str) -> dict[str, str]:
    base = os.environ.get("WHEELSHIP_PBS_MIRROR", GITHUB).rstrip("/")
    text = _get_text(f"{base}/{release}/SHA256SUMS")
    sums: dict[str, str] = {}
    for line in text.splitlines():
        parts = line.split()
        if len(parts) == 2:
            sums[parts[1]] = parts[0].lower()
    return sums


# -- resolution ---------------------------------------------------------------


def resolve(
    cfg: PbsConfig,
    python: tuple[int, ...],
    triple_: str,
    lock_path: Path | None,
    *,
    update_lock: bool = True,
) -> Asset:
    """Find (and pin) the asset for ``python`` on ``triple_``."""
    lock = Lock.load(lock_path) if lock_path else Lock()
    release = cfg.release or lock.release or latest_release()
    if lock.release != release:
        lock = Lock(release)

    asset = select_asset(lock.assets, release, python, triple_, cfg.flavor)
    exact = len(python) == 3
    if asset is None or (not exact and lock_path is None):
        found = select_asset(release_sums(release), release, python, triple_, cfg.flavor)
        if found is None:
            want = ".".join(map(str, python))
            raise ConfigError(
                f"python-build-standalone release {release} has no CPython {want} "
                f"for {triple_} ({cfg.flavor})"
            )
        asset = found
        lock.assets[asset.name] = asset.sha256
        if lock_path is not None and update_lock:
            new_file = not lock_path.exists()
            lock.save(lock_path)
            if new_file:
                log.info(f"pinned python-build-standalone {release} in {lock_path.name}")
    return asset


def download(asset: Asset) -> Path:
    return fetch.fetch(asset.url, asset.name, {"sha256": asset.sha256})


def extract(archive: Path, dest: Path) -> Path:
    """Extract an ``install_only`` archive; returns the ``python`` directory."""
    with tarfile.open(archive) as tf:
        tf.extractall(dest, filter="data")
    root = dest / "python"
    if not root.is_dir():
        raise FetchError(f"{archive.name}: unexpected layout (no top-level 'python/')")
    return root


# -- layout knowledge ---------------------------------------------------------


@dataclasses.dataclass(frozen=True)
class Layout:
    """Paths inside a PBS ``python/`` tree, relative and ``/``-separated."""

    interpreter: str
    gui_interpreter: str | None
    site_packages: str
    scripts: str
    include: str

    @classmethod
    def for_target(cls, target: Target) -> Layout:
        if target.os == "windows":
            return cls("python.exe", "pythonw.exe", "Lib/site-packages", "Scripts", "include")
        minor = target.python_minor
        return cls(f"bin/python{minor}", None, f"lib/python{minor}/site-packages", "bin", "include")


def strip_patterns(target: Target, groups: Iterable[str]) -> list[str]:
    """Glob patterns (relative to ``python/``) for ``groups``; pip is always removed."""
    if target.os == "windows":
        stdlib, site = "Lib", "Lib/site-packages"
        table = {
            "pip": [
                f"{site}/pip/**", f"{site}/pip-*.dist-info/**", "Lib/ensurepip/**", "Scripts/**",
            ],
            "dev": ["include/**", "libs/**"],
            "test": ["Lib/test/**", "Lib/**/tests/**", "Lib/**/idle_test/**"],
            "idlelib": ["Lib/idlelib/**"],
            "tkinter": [
                "Lib/tkinter/**", "DLLs/_tkinter.pyd", "DLLs/tcl*.dll", "DLLs/tk*.dll", "tcl/**",
            ],
        }  # fmt: skip
    else:
        stdlib = f"lib/python{target.python_minor}"
        site = f"{stdlib}/site-packages"
        table = {
            "pip": [
                f"{site}/pip/**", f"{site}/pip-*.dist-info/**", f"{stdlib}/ensurepip/**",
                "bin/pip*",
                # PBS's own scripts carry shebangs of the build machine.
                "bin/2to3*", "bin/idle*", "bin/pydoc*",
            ],
            "dev": [
                "include/**", "lib/pkgconfig/**", "bin/python*-config", "lib/libpython*",
                "lib/**/*.a", f"{stdlib}/config-*/**", "share/man/**",
            ],
            "test": [f"{stdlib}/test/**", f"{stdlib}/**/tests/**", f"{stdlib}/**/idle_test/**"],
            "idlelib": [f"{stdlib}/idlelib/**"],
            "tkinter": [
                f"{stdlib}/tkinter/**", f"{stdlib}/lib-dynload/_tkinter*", "lib/libtcl*",
                "lib/libtk*", "lib/tcl*/**", "lib/tk*/**", "lib/itcl*/**", "lib/thread*/**",
            ],
        }  # fmt: skip
    patterns = list(table["pip"])
    for group in groups:
        if group not in table:
            raise ConfigError(f"unknown strip group {group!r} (known: {', '.join(STRIP_GROUPS)})")
        patterns += table[group]
    return patterns


def trim(python_dir: Path, target: Target, groups: Iterable[str]) -> None:
    # Removing pip (its metadata and licenses included) is intended: no warnings.
    removed = prune.prune(python_dir, strip_patterns(target, groups), warn=False)
    log.debug(f"trimmed {removed} files from python-build-standalone")


# -- host interpreter (bytecode compilation for cross builds) ----------------


def host_interpreter(python: tuple[int, int], release: str | None = None) -> Path:
    """A runnable CPython ``python`` for the host, cached under the wheelship cache."""
    host = host_triple()
    asset = resolve(PbsConfig(release=release), python, host, None)
    root = fetch.cache_dir() / "pbs" / asset.name.removesuffix(".tar.gz")
    if host.endswith("windows-msvc"):
        exe = root / "python" / "python.exe"
    else:
        exe = root / "python" / "bin" / f"python{python[0]}.{python[1]}"
    if exe.is_file():
        return exe
    archive = download(asset)
    root.parent.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix=".extract-", dir=root.parent))
    try:
        extract(archive, tmp)
        try:
            os.replace(tmp, root)
        except OSError:
            if not exe.is_file():  # lost a race with a concurrent build: fine
                raise
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    return exe
